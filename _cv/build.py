def print_page():
    e = html.escape
    parts = ["<!DOCTYPE html>", '<html lang="en"><head><meta charset="utf-8" />',
             "<title>%s — CV</title>" % e(cv.NAME), "<style>",
             font_face("Space Grotesk", "space-grotesk-latin-var.woff2", "300 700"),
             font_face("JetBrains Mono", "jetbrains-mono-latin-400.woff2", "400"),
             PRINT_CSS, "</style></head><body>"]
    parts.append("<header><h1>%s</h1><div class=\"contact\">%s</div></header>"
                 % (e(cv.NAME), e(cv.PDF_CONTACT_LINE)))

    parts.append('<section><div class="label">Education</div>')
    for school, detail in cv.EDUCATION:
        parts.append("<p><b>%s:</b> %s</p>" % (rich(school, False), rich(detail, False)))
    parts.append("</section>")

    parts.append('<section><div class="label">Experience</div>')
    for role in cv.EXPERIENCE:
        parts.append('<div class="role"><div class="role-head"><span class="role-title">%s</span>'
                     '<span class="dates">%s</span></div><div class="org">%s</div><ul>'
                     % (e(role["title"]), e(role.get("dates", "")), rich(role["org"], False)))
        for b in role.get("bullets", []):
            parts.append("<li>%s</li>" % rich(b, False))
        parts.append("</ul></div>")
    parts.append("</section>")

    parts.append('<section><div class="label">Skills</div>')
    for label, text in cv.SKILLS:
        parts.append("<p><b>%s:</b> %s</p>" % (e(label), rich(text, False)))
    parts.append("</section></body></html>")
    return "\n".join(parts)


# ---------------------------------------------------------------- PDF

def find_browser():
    if os.environ.get("CHROME"):
        return os.environ["CHROME"]
    mac = [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
        "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
    ]
    for path in mac:
        if Path(path).exists():
            return path
    for name in ("google-chrome", "google-chrome-stable", "chromium", "chromium-browser", "microsoft-edge", "brave-browser"):
        found = shutil.which(name)
        if found:
            return found
    return None


def build_pdf():
    browser = find_browser()
    if not browser:
        print("  ! No Chrome/Chromium/Edge/Brave found, so the PDF was not rebuilt.\n"
              "    Open _cv/cv_print.html in a browser and Print -> Save as PDF to %s,\n"
              "    or set CHROME=/path/to/browser." % PDF_REL)
        return False
    PDF.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as profile:
        cmd = [browser, "--headless=new", "--disable-gpu", "--no-first-run",
               "--disable-component-update", "--disable-background-networking",
               "--disable-dev-shm-usage", "--no-pdf-header-footer", "--print-to-pdf-no-header",
               "--user-data-dir=" + profile, "--print-to-pdf=" + str(PDF),
               PRINT_HTML.resolve().as_uri()]
        if platform.system() == "Linux" and hasattr(os, "geteuid") and os.geteuid() == 0:
            cmd.insert(1, "--no-sandbox")
        before = PDF.stat().st_mtime if PDF.exists() else None
        try:
            result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=90)
        except subprocess.TimeoutExpired:
            print("  ! The browser timed out while printing. Open _cv/cv_print.html and use\n"
                  "    Print -> Save as PDF, or try another browser with CHROME=/path/to/browser.")
            return False
    fresh = PDF.exists() and PDF.stat().st_mtime != before
    if result.returncode != 0 or not fresh:
        print("  ! The browser could not print the PDF:\n" + result.stderr.decode(errors="replace")[-800:])
        return False
    return True


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-pdf", action="store_true", help="only update index.html")
    ap.add_argument("--check", action="store_true", help="exit 1 if index.html is out of date")
    args = ap.parse_args()

    with open(INDEX, encoding="utf-8", newline="") as f:
        src = f.read()
    new = updated_index(src)

    if args.check:
        if new != src:
            print("index.html is out of date; run python3 _cv/build.py")
            sys.exit(1)
        print("index.html is up to date.")
        return

    if new != src:
        with open(INDEX, "w", encoding="utf-8", newline="") as f:
            f.write(new)
        print("✓ Updated the CV panel in index.html")
    else:
        print("✓ index.html already up to date")

    PRINT_HTML.write_text(print_page(), encoding="utf-8")
    print("✓ Wrote _cv/cv_print.html")

    if not args.no_pdf and build_pdf():
        print("✓ Built %s" % PDF_REL)


if __name__ == "__main__":
    main()
