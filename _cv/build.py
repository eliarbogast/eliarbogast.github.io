#!/usr/bin/env python3
"""
Build the CV for eliarbogast.com from _cv/cv_data.py.

    python3 _cv/build.py            # update index.html + rebuild the PDF
    python3 _cv/build.py --no-pdf   # only update index.html
    python3 _cv/build.py --check    # exit 1 if index.html is out of date (no changes made)

What it does
  1. Rewrites everything between the CV:START / CV:END markers in index.html.
  2. Writes _cv/cv_print.html, a print-styled page (fonts embedded).
  3. Prints that page to cv/Eli_Arbogast_CV.pdf with headless Chrome/Chromium/Edge/Brave
     if one is installed (set CHROME=/path/to/browser to choose one). If none is found,
     open _cv/cv_print.html in a browser and use Print -> Save as PDF instead.

Standard library only; works with any Python 3.8+.
"""

import argparse
import base64
import html
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
INDEX = ROOT / "index.html"
PRINT_HTML = HERE / "cv_print.html"
PDF_REL = "cv/Eli_Arbogast_CV.pdf"
PDF = ROOT / PDF_REL

START = "<!-- CV:START (generated by _cv/build.py from _cv/cv_data.py; edit that file, not this block) -->"
END = "<!-- CV:END -->"

sys.path.insert(0, str(HERE))
import cv_data as cv  # noqa: E402


# ---------------------------------------------------------------- text helpers

LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def rich(text, new_tab=True):
    """Escape text for HTML and turn [label](url) into links."""
    out = html.escape(text, quote=False)
    target = ' target="_blank" rel="noopener"' if new_tab else ""
    return LINK.sub(lambda m: '<a href="%s"%s>%s</a>' % (html.escape(m.group(2)), target, m.group(1)), out)


def plain(text):
    """Text with link markup removed (for places that can't hold links)."""
    return LINK.sub(lambda m: m.group(1), text)


# ---------------------------------------------------------------- website block

def site_block():
    t = "\t"
    L = []
    a = t * 7  # <article> indent inside #main

    L.append(a + '<article id="cv" class="panel body">')
    L.append(a + t + '<header class="cv-header">')
    L.append(a + t * 2 + "<h1>CV</h1>")
    L.append(a + t * 2 + '<a class="cv-download" href="%s" download>Download PDF <span aria-hidden="true">&darr;</span></a>' % PDF_REL)
    L.append(a + t + "</header>")
    L.append("")

    L.append(a + t + '<section class="cv-skills">')
    L.append(a + t * 2 + '<h3 class="cv-label">Skills</h3>')
    for label, text in cv.SKILLS:
        L.append(a + t * 2 + "<p><b>%s:</b> %s</p>" % (html.escape(label), rich(text)))
    L.append(a + t + "</section>")
    L.append("")

    L.append(a + t + '<section class="cv-education">')
    L.append(a + t * 2 + '<h3 class="cv-label">Education</h3>')
    L.append(a + t * 2 + "<p>")
    rows = ["<b>%s:</b> %s" % (rich(school), rich(detail)) for school, detail in cv.EDUCATION]
    for i, row in enumerate(rows):
        L.append(a + t * 3 + row + ("<br />" if i < len(rows) - 1 else ""))
    L.append(a + t * 2 + "</p>")
    L.append(a + t + "</section>")
    L.append("")

    L.append(a + t + "<hr />")
    L.append("")

    L.append(a + t + '<section class="cv-experience">')
    L.append(a + t * 2 + '<h3 class="cv-label">Experience</h3>')
    for role in cv.EXPERIENCE:
        org = rich(role["org"])
        if role.get("dates"):
            org += " · " + html.escape(role["dates"])
        L.append(a + t * 2 + '<div class="cv-role">')
        L.append(a + t * 3 + '<h3>%s <span class="org">%s</span></h3>' % (html.escape(role["title"]), org))
        L.append(a + t * 3 + "<ul>")
        for b in role.get("bullets", []):
            L.append(a + t * 4 + "<li>%s</li>" % rich(b))
        L.append(a + t * 3 + "</ul>")
        L.append(a + t * 2 + "</div>")
    L.append(a + t + "</section>")
    L.append(a + "</article>")
    return L


def updated_index(src):
    if START not in src or END not in src:
        sys.exit("index.html is missing the CV:START / CV:END markers.")
    nl = "\r\n" if "\r\n" in src else "\n"
    head, rest = src.split(START, 1)
    _, tail = rest.split(END, 1)
    indent = head[head.rfind("\n") + 1:]  # whitespace before the START marker
    body = nl.join(site_block())
    return head + START + nl + body + nl + nl + indent + END + tail


# ---------------------------------------------------------------- print page

def font_face(family, filename, weight):
    path = ROOT / "assets" / "webfonts" / filename
    if not path.exists():
        return ""
    data = base64.b64encode(path.read_bytes()).decode()
    return ("@font-face{font-family:'%s';src:url(data:font/woff2;base64,%s) format('woff2');"
            "font-weight:%s;font-style:normal;}" % (family, data, weight))


